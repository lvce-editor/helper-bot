// Input: GitHub's api.github.com OpenAPI document at the revision recorded in the documentation.
import { readFileSync, writeFileSync } from 'node:fs'

const document = JSON.parse(readFileSync(process.argv[2], 'utf8'))
const resolve = (schema) => {
  if (Array.isArray(schema)) return schema.map(resolve)
  if (!schema || typeof schema !== 'object') return schema
  if (schema.$ref)
    return resolve(
      schema.$ref
        .split('/')
        .slice(1)
        .reduce((value, key) => value[key], document),
    )
  const result = Object.fromEntries(
    Object.entries(schema)
      .filter(([key]) => !['description', 'example', 'examples', 'title', 'default', 'deprecated'].includes(key))
      .map(([key, value]) => [key, resolve(value)]),
  )
  // Privileged API data must reject unknown keys, including inside rule parameters.
  if (result.type === 'object' && result.properties) result.additionalProperties = false
  return result
}
const schema = resolve(document.paths['/repos/{owner}/{repo}/rulesets'].post.requestBody.content['application/json'].schema)
schema.required = ['name', 'target', 'enforcement', 'bypass_actors', 'conditions', 'rules']
const license = readFileSync(new URL('./repository-ruleset-schema.LICENSE.txt', import.meta.url), 'utf8')
writeFileSync(
  new URL('../packages/app/src/parts/RepositoryConfig/RepositoryRulesetSchema.ts', import.meta.url),
  `// Generated by scripts/generateRepositoryRulesetSchema.js. See docs/repository-configuration.md.\n/*\n${license}*/\nexport const rulesetSchema = ${JSON.stringify(schema, null, 2)}\n`,
)
